#!/usr/bin/env node
// Deterministic build input: no network, account lookup or runtime settings.
import {readFileSync,writeFileSync} from "node:fs";
import {dirname,resolve} from "node:path";
import {fileURLToPath} from "node:url";
import {parseFunding,supportManifest} from "../steamdeck/decky/src/support.mjs";

export function generateSupport(root,{check=false}={}) {
  const funding=parseFunding(readFileSync(resolve(root,".github/FUNDING.yml"),"utf8"));
  const config=JSON.parse(readFileSync(resolve(root,"support.json"),"utf8"));
  const manifest=supportManifest(funding,config);
  const output="// Generated by scripts/generate-support.mjs. Edit .github/FUNDING.yml or support.json.\n"+
    "export default "+JSON.stringify(manifest,null,2)+";\n";
  const path=resolve(root,"steamdeck/decky/src/support-data.mjs");
  if(check) {
    if(readFileSync(path,"utf8")!==output)throw new Error("Support data is stale. Run node scripts/generate-support.mjs.");
  } else writeFileSync(path,output);
  return manifest;
}

if(process.argv[1] && resolve(process.argv[1])===fileURLToPath(import.meta.url)) {
  const args=process.argv.slice(2);
  if(args.some(arg=>arg!=="--check"))throw new Error("Usage: node scripts/generate-support.mjs [--check]");
  generateSupport(resolve(dirname(fileURLToPath(import.meta.url)),".."),{check:args.includes("--check")});
}
