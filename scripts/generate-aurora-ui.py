#!/usr/bin/env python3
"""Project the selected local artwork into the UI; never change installed IDs."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import stat
import sys
import tempfile
from urllib.parse import quote
import xml.etree.ElementTree as ET

sys.path.insert(0, str(Path(__file__).resolve().parent))
from brand_png import validate_png

ROOT = Path(__file__).resolve().parents[1]
PREFIX = "// Generated by scripts/generate-aurora-ui.py. Edit the selected artwork, not this file.\n"


def safe_path(path):
    for candidate in (path, *path.parents):
        if candidate.is_symlink():
            raise ValueError("Brand projection refuses linked input/output paths")
        if candidate == ROOT:
            break


def regular(path):
    safe_path(path)
    info = path.stat()
    if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
        raise ValueError("Brand projection requires single-link regular files")
    return path.read_bytes()


def icon_data(raw):
    if len(raw) > 65536 or re.search(br"<!DOCTYPE|<!ENTITY|<\?", raw, re.I):
        raise ValueError("Unexpected compact SVG source")
    document = ET.fromstring(raw)
    if document.tag != "{http://www.w3.org/2000/svg}svg" or document.get("viewBox") != "0 0 256 256":
        raise ValueError("Expected the selected compact SVG profile")
    allowed = {"svg", "defs", "linearGradient", "radialGradient", "stop", "path", "g", "rect", "circle", "ellipse", "title", "desc"}
    ids = [node.get("id") for node in document.iter() if node.get("id")]
    if len(ids) != len(set(ids)):
        raise ValueError("Compact mark IDs must be unique")
    references = []
    for node in document.iter():
        if node.tag.removeprefix("{http://www.w3.org/2000/svg}") not in allowed:
            raise ValueError("Compact mark must contain only local vector geometry")
        for name, value in node.attrib.items():
            if name.startswith("{") or name.lower().startswith("on") or "href" in name.lower() or name == "style" or "\\" in value or "//" in value:
                raise ValueError("Compact mark cannot contain active or referenced content")
            if "url(" in value.lower() and not re.fullmatch(r"url\(#[A-Za-z][A-Za-z0-9_-]*\)", value):
                raise ValueError("Compact mark references must stay local")
            if value.startswith("url(#"):
                references.append(value[5:-1])
    if any(reference not in ids for reference in references):
        raise ValueError("Compact mark references must resolve inside the source")
    return "data:image/svg+xml," + quote(raw.decode("utf-8"), safe="")


def png(raw):
    return validate_png(raw)


def outputs(root=ROOT):
    raw = regular(root / ".identity/candidates/aurora/mark-small.svg")
    module = PREFIX + "export const auroraIcon = " + json.dumps(icon_data(raw)) + ";\n"
    module += "export const auroraSourceSHA256 = " + json.dumps(hashlib.sha256(raw).hexdigest()) + ";\n"
    return {
        "steamdeck/decky/src/aurora-brand.mjs": module.encode(),
        "site/assets/brand-icon.png": png(regular(root / "branding/aurora/web/favicon-32.png")),
        "site/assets/brand-hero.png": png(regular(root / "branding/aurora/github/readme-header.png")),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, content in outputs().items():
        path = ROOT / name
        safe_path(path)
        if path.exists() or path.is_symlink():
            existing = regular(path)
            if not args.check and path.stat().st_uid != os.getuid():
                raise ValueError("Brand projection must own its generated output")
            if args.check and existing != content:
                raise SystemExit("Regenerate selected UI assets: python3 scripts/generate-aurora-ui.py")
        elif args.check:
            raise SystemExit("Missing selected UI asset: " + name)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            with tempfile.NamedTemporaryFile(prefix=".aurora-", dir=path.parent, delete=False) as output:
                temporary = Path(output.name)
                try:
                    output.write(content)
                    output.flush()
                    os.fchmod(output.fileno(), 0o644)
                    os.replace(temporary, path)
                finally:
                    temporary.unlink(missing_ok=True)


if __name__ == "__main__":
    main()
