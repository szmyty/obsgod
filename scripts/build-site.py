#!/usr/bin/env python3
"""Build/check an offline static preview. No dependencies, network or deployment."""
import argparse
import hashlib
import html
from html.parser import HTMLParser
import json
from pathlib import Path, PurePosixPath
import re
import subprocess
from urllib.parse import unquote, urlsplit


ROOT = Path(__file__).resolve().parents[1]
GENERATED_PREFIX = "// Generated by scripts/generate-support.mjs. Edit .github/FUNDING.yml or support.json.\nexport default "


def text(value, label, limit=300):
    if not isinstance(value, str) or not value or len(value) > limit or not value.isprintable():
        raise ValueError("Invalid " + label)
    return html.escape(value, quote=True)


def https_url(value):
    if not isinstance(value, str) or any(ord(char) < 33 for char in value):
        raise ValueError("Invalid external URL")
    try:
        parsed = urlsplit(value)
        if (parsed.scheme != "https" or not parsed.hostname or parsed.username or parsed.password
                or parsed.port or parsed.fragment):
            raise ValueError()
    except ValueError:
        raise ValueError("Expected a plain HTTPS destination without credentials") from None
    return html.escape(value, quote=True)


def source_state(root):
    try:
        revision = subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=root, stderr=subprocess.DEVNULL, text=True).strip()
        dirty = bool(subprocess.check_output(
            ["git", "status", "--porcelain=v1"], cwd=root, stderr=subprocess.DEVNULL, text=True))
        if not re.fullmatch(r"[0-9a-f]{40}", revision):
            raise ValueError("Invalid source revision")
        return {"revision": revision, "dirty": dirty}
    except (OSError, subprocess.CalledProcessError):
        return {"revision": "unversioned-source", "dirty": None}


def support_html(root):
    raw = (root / "steamdeck/decky/src/support-data.mjs").read_text()
    if not raw.startswith(GENERATED_PREFIX) or not raw.endswith(";\n"):
        raise ValueError("Support data must be generated by scripts/generate-support.mjs")
    support = json.loads(raw[len(GENERATED_PREFIX):-2])
    if not isinstance(support, dict) or support.get("schema_version") != 1:
        raise ValueError("Unsupported support schema")
    providers, wallets = support.get("providers"), support.get("wallets")
    if not isinstance(providers, list) or len(providers) > 20 or not isinstance(wallets, list) or len(wallets) > 3:
        raise ValueError("Invalid support entries")
    buttons = []
    for provider in providers:
        if not isinstance(provider, dict):
            raise ValueError("Invalid funding destination")
        buttons.append('<a class="button" href="' + https_url(provider.get("url")) +
                       '"><span class="support-symbol" aria-hidden="true">' +
                       text(provider.get("symbol"), "support symbol", 8) + '</span>' +
                       text(provider.get("label"), "support label", 80) + '</a>')
    if wallets:
        buttons.append('<div class="wallets"><h3>Cryptocurrency</h3>')
        for wallet in wallets:
            if not isinstance(wallet, dict) or wallet.get("coin") not in {"bitcoin", "ethereum", "solana"}:
                raise ValueError("Invalid cryptocurrency destination")
            address = text(wallet.get("address"), "public receiving address", 200)
            buttons.append('<section class="wallet"><h3>' +
                           text(wallet.get("label"), "coin label", 80) + '</h3><p>Network: ' +
                           text(wallet.get("networkLabel"), "network label", 100) +
                           '</p><code>' + address + '</code><button type="button" class="button" data-copy="' +
                           address + '">Copy address</button><p class="copy-status" role="status" aria-live="polite"></p></section>')
        buttons.append('</div>')
    if not buttons:
        return '<p>Funding destinations have not been configured.</p>'
    return "".join(buttons)


class Document(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.ids = set()
        self.links = []
        self.h1 = self.main = 0
        self.language = None

    def handle_starttag(self, tag, attrs):
        values = dict(attrs)
        if "id" in values:
            if values["id"] in self.ids:
                raise ValueError("Duplicate document ID")
            self.ids.add(values["id"])
        if tag == "html":
            self.language = values.get("lang")
        if tag == "h1":
            self.h1 += 1
        if tag == "main":
            self.main += 1
        if "style" in values or any(key.lower().startswith("on") for key in values):
            raise ValueError("Inline script/style is not allowed by the preview policy")
        for attr in ("href", "src"):
            if values.get(attr):
                self.links.append((values[attr], tag == "a" and attr == "href"))


def check_links(files):
    documents = {}
    for name, data in files.items():
        if name.endswith(".html"):
            doc = Document()
            doc.feed(data.decode("utf-8"))
            if doc.h1 != 1 or doc.main != 1 or doc.language != "en":
                raise ValueError("Each page needs one h1, one main landmark and an explicit language: " + name)
            documents[name] = doc
    links = external = 0
    for name, doc in documents.items():
        for value, is_navigation in doc.links:
            if value == "data:," and not is_navigation:
                # An empty local favicon suppresses the browser's implicit
                # /favicon.ico fetch without creating provisional brand art.
                continue
            parsed = urlsplit(value)
            if parsed.scheme or parsed.netloc:
                if not is_navigation:
                    raise ValueError("Remote assets are not allowed: " + name)
                https_url(value)
                external += 1
                continue
            path = unquote(parsed.path)
            target = str(PurePosixPath(name).parent / path) if path else name
            if path.startswith("/") or ".." in PurePosixPath(target).parts or target not in files:
                raise ValueError("Missing or unsafe local link in " + name + ": " + value)
            if parsed.fragment and (target not in documents or unquote(parsed.fragment) not in documents[target].ids):
                raise ValueError("Missing anchor in " + name + ": " + value)
            links += 1
    return {"pages": len(documents), "local_links": links, "external_links_syntax_checked": external}


def render(root=ROOT):
    product_path = root / "product.json"
    product = json.loads(product_path.read_text())
    if not isinstance(product, dict) or product.get("schema_version") != 1:
        raise ValueError("Unsupported product schema")
    display_name = text(product.get("display_name"), "display name", 80)
    repository = product.get("repository")
    if not isinstance(repository, str) or not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", repository):
        raise ValueError("Invalid canonical repository")
    pages = json.loads((root / "site/pages.json").read_text())
    if not isinstance(pages, dict) or not 1 <= len(pages) <= 30:
        raise ValueError("Invalid page index")
    for name, page in pages.items():
        if not re.fullmatch(r"[a-z][a-z-]*\.html", name) or not isinstance(page, dict):
            raise ValueError("Invalid page definition")
        text(page.get("title"), "page title", 120)
        text(page.get("description"), "page description")
        text(page.get("navigation"), "navigation label", 40)
    base_url = "https://github.com/" + repository
    source = source_state(root)
    ref = source["revision"] if source["revision"] != "unversioned-source" else "HEAD"
    values = {
        "DISPLAY_NAME": display_name,
        "SOURCE_URL": base_url + "/tree/" + ref,
        "ISSUES_URL": base_url + "/issues",
        "LICENSE_URL": base_url + "/blob/" + ref + "/LICENSE",
        "DECK_GUIDE_URL": base_url + "/blob/" + ref + "/docs/steam-deck.md",
        "QUALIFICATION_URL": base_url + "/issues/46",
        "REVISION": html.escape(source["revision"]),
        "DIRTY_NOTE": " (working tree includes uncommitted files)" if source["dirty"] else "",
        "SUPPORT": support_html(root),
    }
    template = (root / "site/template.html").read_text()
    files = {}
    for name, page in pages.items():
        navigation = []
        for target, entry in pages.items():
            current = ' aria-current="page"' if name == target else ""
            navigation.append('<a href="' + target + '"' + current + '>' +
                              text(entry.get("navigation"), "navigation label", 40) + '</a>')
        tokens = {**values, "TITLE": text(page.get("title"), "page title", 120),
                  "DESCRIPTION": text(page.get("description"), "page description"),
                  "NAVIGATION": "".join(navigation),
                  "MAIN": (root / "site/content" / name).read_text()}
        rendered = template
        # Insert trusted hand-authored content before escaping metadata tokens.
        for key in ("MAIN", "NAVIGATION", "SUPPORT"):
            rendered = rendered.replace("@@" + key + "@@", tokens.pop(key))
        for key, value in tokens.items():
            rendered = rendered.replace("@@" + key + "@@", value)
        if re.search(r"@@[A-Z_]+@@", rendered):
            raise ValueError("Unresolved template token in " + name)
        files[name] = rendered.encode("utf-8")
    for path in sorted((root / "site/assets").rglob("*")):
        if path.is_file():
            if path.is_symlink() or path.suffix not in {".css", ".js"}:
                raise ValueError("Unexpected site asset")
            data = path.read_bytes()
            if path.suffix == ".css" and re.search(r"url\s*\(|@import", data.decode("utf-8"), re.IGNORECASE):
                raise ValueError("Preview CSS must not fetch additional assets")
            files["assets/" + path.relative_to(root / "site/assets").as_posix()] = data
    validation = check_links(files)
    inputs = [product_path, root / "support.json", root / ".github/FUNDING.yml",
              root / "steamdeck/decky/src/support-data.mjs", root / "scripts/build-site.py"]
    inputs += sorted(p for p in (root / "site").rglob("*")
                     if p.is_file() and "__pycache__" not in p.parts and p.suffix != ".pyc")
    manifest = {"schema_version": 1, "kind": "offline-documentation-preview", "source": source,
                "display_name": product["display_name"], "published": False, "validation": validation,
                "inputs": {p.relative_to(root).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest() for p in inputs},
                "files": {name: hashlib.sha256(data).hexdigest() for name, data in sorted(files.items())}}
    files["site-manifest.json"] = (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode()
    return files, validation


def write_or_check(files, output, check=False):
    if output.is_symlink():
        raise ValueError("Output directory cannot be a symlink")
    existing = {p.relative_to(output).as_posix() for p in output.rglob("*") if p.is_file() or p.is_symlink()}
    if existing - files.keys():
        raise ValueError("Output contains unrelated files; choose an empty preview directory")
    if check:
        if existing != files.keys() or any((output / name).is_symlink() or (output / name).read_bytes() != data
                                          for name, data in files.items()):
            raise ValueError("Site preview is stale; rebuild it from the current source")
        return
    for name, data in files.items():
        target = output / name
        if target.is_symlink():
            raise ValueError("Output files/directories cannot be symlinks")
        for parent in target.parents:
            if parent == output:
                break
            if parent.is_symlink():
                raise ValueError("Output files/directories cannot be symlinks")
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "dist/site")
    parser.add_argument("--check", action="store_true", help="Verify existing output exactly without changing it")
    args = parser.parse_args()
    try:
        files, validation = render()
        write_or_check(files, args.output.absolute(), args.check)
    except (OSError, ValueError, TypeError, KeyError) as error:
        parser.exit(1, "Site preview failed: " + str(error) + "\n")
    print(json.dumps({"status": "checked" if args.check else "built", "output": str(args.output),
                      "files": len(files), **validation}, sort_keys=True))


if __name__ == "__main__":
    main()
